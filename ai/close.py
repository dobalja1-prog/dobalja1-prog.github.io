def _format_snapshot(snapshot: dict) -> str:
    lines = []
    for key, label in [("kospi", "코스피"), ("kosdaq", "코스닥")]:
        s = snapshot[key]
        lines.append(
            f"[{label}] 현재가 {s['current']} ({s['change_direction']} {s['change']}, "
            f"{s['change_pct']}%) / 시가 {s['open']} 고가 {s['high']} 저가 {s['low']} / "
            f"상승 {s['rise_count']}개 하락 {s['fall_count']}개 "
            f"보합 {s['steady_count']}개 (상한 {s['upper_limit_count']} 하한 {s['lower_limit_count']}) / "
            f"외국인 순매수 {s['foreign_net']}억원, 기관 순매수 {s['institution_net']}억원, "
            f"개인 순매수 {s['personal_net']}억원"
        )
    return "\n".join(lines)


def _format_articles(articles: list[dict]) -> str:
    if not articles:
        return "(수집된 관련 기사 없음)"
    return "\n\n".join(
        f"[기사 {i+1}] {a['title']}\n{a['text']}" for i, a in enumerate(articles)
    )


