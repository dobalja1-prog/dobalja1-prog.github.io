from pydantic import BaseModel

from ai.client import ask_structured
from ai.sections import SECTIONS


class BriefingSection(BaseModel):
    content: str


class KeyStat(BaseModel):
    label: str  # 예: "다우", "나스닥", "코스피"
    value: str  # 예: "53,185.90"
    change: str  # 예: "-0.70%" (부호를 반드시 포함)


class MarketBriefing(BaseModel):
    headline: str  # 오늘 시황을 한 문장으로 요약
    sentiment: str  # "상승" | "하락" | "혼조" 중 하나
    key_stats: list[KeyStat]
    sections: list[BriefingSection]
    chat_summary: str  # 단체방에 바로 붙여넣을 수 있는 개인 스타일 요약본


STYLE_EXAMPLE = '''좋은 아침입니다.

간밤에 미증시는 중동 긴장 재고조에 따른 지정학적 리스크 부각과 국채금리 상승이 불거지며 3대지수 약세 마감했습니다.

중동 리스크 재부각으로 유가가 86% 대까지 +2% 가량 오르며 인플레이션 부담 요인으로 다시 올라왔고 금리 미 국채 10년물이 4.76%로 소폭 더 상승해 고금리 장기화 부담이 이어졌는데 시장이 "불편"한 수준이지 "공포" 수준은 아닙니다.

시장이 두려워한다고 느끼는 수준의 금리 레벨은 10년물 5%, 유가는 90불입니다.
특히 금리는 이미 잭슨홀미팅에서 올린다고 미리 언질을 준 상황이니 지금 수준은 시장이 납득하는 수준이죠.

지수 전반적으로는 약세였지만 빠졌다기 보단 대형 SW 주에서 반도체/성장주쪽으로는 자금이 들어왔고 지수 선물이 소폭 상승 중이라는 점도 야간 심리가 급격히 나빠지지는 않았음을 보여주고 있네요.

다만 여기서 유가가 더 오르게 되면 인플레우려가 더 강해지고 금리가 4.7%대에 고착될 경우 밸류에이션 부담이 큰 업종부터 조정이 길어질 수 있습니다.

오늘 국내 증시는 미국 반도체 강세를 반영해 반도체 대형주 중심의 견조한 출발 가능성을 감안할 필요가 있습니다. 다만 지수 전반은 지정학 리스크와 금리 부담으로 상단이 제한될 수 있어, 지수 방향보다는 업종 선택이 중요한 국면으로 보이고 최근 강세였던 중소형 테마는 코스닥 신용융자 증가가 지적되고 있는 만큼, 변동성이 커질 경우 되돌림이 빠를 수 있다는 점을 함께 볼 필요가 있습니다.

오늘도 화이팅하시기 바랍니다!'''


def _build_prompt(articles: list[dict]) -> str:
    article_block = "\n\n".join(
        f"[기사 {i+1}] {a['title']}\n{a['text']}"
        for i, a in enumerate(articles)
    )

    section_block = "\n".join(
        f"{i+1}. {s['title']} — {s['instruction']}" for i, s in enumerate(SECTIONS)
    )

    return f"""당신은 국내 증권사의 리서치 담당자입니다.
아래는 오늘 아침 수집된 관련 기사 원문들입니다. 이 기사들을 바탕으로
국내증시 개장 전 시황 브리핑을 본인이 직접 작성하는 것처럼 쓰세요.

[중요 - 문체]
- "연합인포맥스", "로이터", "AP", "블룸버그", "OO통신", "OO에 따르면" 같은
  언론사/통신사 이름이나 출처 표현은 절대 쓰지 마세요. 여러 기사를 짜깁기한
  게 아니라, 본인이 직접 분석해서 쓴 브리핑처럼 자연스럽게 서술하세요.
- 숫자·사실관계는 정확히 유지하되, 문장은 스스로 재구성하세요.
- "-했다", "-였다", "-이었다" 같은 딱딱한 기사체(신문 기사, 개조식) 어미는
  쓰지 마세요.
- 문장을 끝맺을 때(마침표 앞)는 기본적으로 "-습니다" 체를 쓰세요.
  "-했어요", "-됐어요", "-네요" 처럼 캐주얼한 "-요"체로 문장을 끝내지
  마세요.
- 다만 "-습니다."만 계속 반복되면 단조로우니, 가끔은 "-이죠.", "-했죠."
  같은 어미로 문장을 끝내서 자연스럽게 변화를 주세요. 비율은 "-습니다"가
  더 많되, 매 문단 전부 "-습니다"로만 끝나지 않도록 하세요.
- 다만 문장 중간에는 "-했고,", "-됐고,", "-는데," 같은 자연스러운
  구어체 연결어미를 적절히 섞어서, 딱딱하게 나열만 하는 느낌이 들지
  않게 하세요.
- 특히 종목·수치를 여러 개 나열할 때(예: "A는 올랐고, B는 내렸고, C도
  올랐다" 같은 경우) 절대로 항목마다 문장을 끊어서 "-습니다."를 연달아
  3번 이상 반복하지 마세요. 그러면 기계적으로 나열한 것처럼 보입니다.
  서로 관련된 항목은 "-했고," "-한 반면," 같은 연결어미로 최대한 묶어서
  하나의 긴 문장으로 이어 쓰고, 완전히 다른 이야기로 넘어갈 때만
  "-습니다."로 끊으세요.
- "-고요", "-는데요"처럼 "요"가 붙는 연결어미는 반드시 뒤에 문장이
  더 이어질 때만 쓰세요. "...마쳤고요." 처럼 "요" 바로 뒤에 마침표를
  붙여서 문장을 끝내는 건 절대 금지입니다. 그 자리에서 끝내고 싶으면
  "요"를 빼고 "...마쳤고," 라고 쓰고 문장을 이어가거나, 아예
  "-습니다."로 마무리하세요.

[작성할 것]
- headline: 오늘 시황 전체를 한 문장으로 요약
- sentiment: "상승" / "하락" / "혼조" 중 하나만
- key_stats: 기사에 나온 주요 지수(다우, 나스닥, S&P500, 코스피 등)의
  수치와 등락률을 최대 5개까지. change는 반드시 +/- 부호 포함
  (예: "-0.70%", "+0.46%")
- sections: 아래 [작성할 항목]과 정확히 같은 순서, 같은 개수로
  content만 작성하세요 (제목은 이미 정해져 있으니 쓰지 마세요).
  각 항목은 2~4문장. 기사에 없는 내용은 추측하지 말고 근거가
  부족하면 "관련 정보 부족"이라고 명시하세요.
- chat_summary: 단체 채팅방에 바로 붙여넣을 수 있는 개인 브리핑 요약본.
  아래 [문체 예시]는 어투와 문단 구성을 참고하기 위한 예시일 뿐입니다.
  예시 속 구체적인 수치(유가 86%, 금리 4.76%, 10년물 5%, 유가 90불 등)는
  그날그날 다른 값이니 절대 그대로 베끼지 말고, 오늘 수집된 기사 내용에
  맞는 실제 수치와 판단으로 새로 작성하세요.
  - "좋은 아침입니다."로 시작해서 "오늘도 화이팅하시기 바랍니다!"로 끝내세요.
  - 문단 사이는 한 줄씩 띄우세요.
  - 단순히 사실을 나열하지 말고, "이 정도면 시장이 불편해하는 수준이지
    공포 수준은 아니다" 처럼 본인의 판단과 해석을 자신 있게 섞어서
    쓰세요. 어떤 수준부터 시장이 더 불안해질지, 그 기준도 오늘 기사에
    나온 정보를 바탕으로 직접 제시하세요.
  - 앞의 [중요 - 문체] 규칙을 여기서도 동일하게 지키세요.

[문체 예시]
{STYLE_EXAMPLE}

[작성할 항목]
{section_block}

[수집된 기사 원문]
{article_block}
"""


async def generate_briefing(articles: list[dict]) -> MarketBriefing:
    prompt = _build_prompt(articles)
    return await ask_structured(prompt, MarketBriefing)
