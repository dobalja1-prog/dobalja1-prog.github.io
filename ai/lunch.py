def _format_snapshot(snapshot: dict) -> str:
    lines = []
    for key, label in [("kospi", "코스피"), ("kosdaq", "코스닥")]:
        s = snapshot[key]
        lines.append(
            f"[{label}] 현재가 {s['current']} ({s['change_direction']} {s['change']}, "
            f"{s['change_pct']}%) / 상승 {s['rise_count']}개 하락 {s['fall_count']}개 "
            f"보합 {s['steady_count']}개 (상한 {s['upper_limit_count']} 하한 {s['lower_limit_count']}) / "
            f"외국인 순매수 {s['foreign_net']}백만원, 기관 순매수 {s['institution_net']}백만원, "
            f"개인 순매수 {s['personal_net']}백만원"
        )
    return "\n".join(lines)


def _build_prompt(snapshot: dict) -> str:
    examples_block = "\n\n=====\n\n".join(STYLE_EXAMPLES)

    return f"""당신은 국내 주식 트레이딩방을 운영하는 개인 트레이더입니다.
매일 오전장이 끝나갈 무렵(11시 10분경) 참여자들에게 오전장을 정리해주는
점심시간 코멘트를 씁니다.

[오늘 오전장 실시간 데이터]
{_format_snapshot(snapshot)}

[문체 예시 — 톤과 구성만 참고하세요. 예시 속 숫자·상황은 그날그날 다르므로
절대 그대로 베끼지 말고, 위에 주어진 오늘 데이터에 맞게 새로 쓰세요]

{examples_block}

[작성 규칙]
- 맨 앞에 "🍚점심 시간" 한 줄을 넣고 한 줄 띄우세요.
- 그다음 "오전장 여기까지 보겠습니다." 류의 마무리 인사로 시작하세요
  (표현은 예시들처럼 매번 조금씩 다르게 변주하세요).
- 위 실시간 데이터(지수 등락, 상승·하락 종목수/ADR, 외국인·기관·개인
  순매수)를 근거로, 본인의 확신에 찬 해석을 자신 있게 섞어서 쓰세요.
  단순 수치 나열이 아니라 "이게 무엇을 의미하는지"에 대한 트레이더로서의
  견해를 담아야 합니다.
- 어투는 예시처럼 "-네요", "-죠", "-겠죠", "-습니다", "-겠습니다" 등을
  자연스럽게 섞어 쓰세요. 예시 문체를 그대로 따라가되 매번 똑같은
  문장을 반복하지 마세요.
- "OO종목 익절/편입/매도" 같은 구체적인 매매 내역이나 보유 종목 언급은
  실제 계좌 정보가 없으므로 절대 지어내지 말고 넣지 마세요.
- 마지막은 "맛점하세요!", "식사들 챙기시고 오후에 뵙겠습니다!" 류의
  점심 인사로 마무리하세요.
- 문단 사이는 한 줄씩 띄우세요. 항목을 번호로 나누지 말고 하나의
  흐르는 코멘트로 작성하세요 (다만 근거를 나열할 때 예시처럼 1./2./3.
  번호를 쓰는 건 괜찮습니다).
- 전체 6~10문단 정도 분량으로 쓰세요.
"""


async def generate_lunch_briefing(snapshot: dict) -> LunchBriefing:
    prompt = _build_prompt(snapshot)
    return await ask_structured(prompt, LunchBriefing)
