def _format_history(recent_history: list[dict]) -> str:
    if not recent_history:
        return "(최근 기록 없음 — 참고할 과거 브리핑이 아직 없습니다)"
    parts = []
    for entry in recent_history:
        text = entry["text"]
        if len(text) > 1000:
            text = text[:1000] + "...(생략)"
        parts.append(f"[{entry['date']}]\n{text}")
    return "\n\n".join(parts)


